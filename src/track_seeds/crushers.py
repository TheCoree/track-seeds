"""Дробилки предприятия. Камеры, зоны и эталоны вшиты в программу — это настоящие дробилки в работе.

Камеры Hikvision смотрят сверху в открытый желоб под бункером: в желобе семена и вал
с лопастью, рядом — цепь со звёздочкой. Сам бункер непрозрачный, поэтому зона одна — в желобе:
пока в бункере есть семена, желоб полный, кончились — желоб пустеет. Зона «привод» на цепи
показывает, работает ли дробилка: пока стоит, о семенах не сообщается.

Анализ идёт по субпотоку 640×360: признаки зон всё равно считаются в масштабе кадра шириной 640,
а декодировать его в ~10 раз дешевле основного 2560×1440 — на сервере с двумя ядрами это главное.

Поправить зону — здесь: углы в пикселях кадра 2560×1440 (доли кадра те же в любом потоке).
Эталоны — кадры в builtin/<id>/samples/, сняты 29.10.2026 днём при полном желобе и работающей
дробилке: по 4 с основного потока и с субпотока. Что меняется на месте (пароль камеры, фразы,
динамики, эталоны, снятые потом), лежит в CONFIG_DIR/crushers/<id>/.
"""

from dataclasses import dataclass
from pathlib import Path

from .config import SeedSample, SeedZone

BUILTIN_DIR = Path(__file__).parent / "builtin"
_W, _H = 2560, 1440


def _zone(zone_id: str, name: str, kind: str, *corners: tuple[int, int]) -> SeedZone:
    return SeedZone(id=zone_id, name=name, kind=kind,  # type: ignore[arg-type]
                    points=[(round(x / _W, 4), round(y / _H, 4)) for x, y in corners])


def _full(*samples: tuple[str, float]) -> tuple[SeedSample, ...]:
    """Эталоны «семена есть» для зоны желоба."""
    return tuple(SeedSample(id=sample_id, image=f"samples/{sample_id}.jpg", ts=ts, labels={"zhelob": "full"},
                            builtin=True) for sample_id, ts in samples)


@dataclass(frozen=True)
class CrusherSpec:
    id: str  # имя папки в CONFIG_DIR/crushers/ и в адресах веб-интерфейса
    name: str
    camera_url: str
    zones: tuple[SeedZone, ...]
    samples: tuple[SeedSample, ...]
    username: str = "admin"
    builtin_root: Path = BUILTIN_DIR

    @property
    def builtin_dir(self) -> Path:
        """Папка вшитых эталонов: <builtin_root>/<id>/samples/…"""
        return self.builtin_root / self.id


